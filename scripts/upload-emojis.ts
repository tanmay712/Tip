import "dotenv/config";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { REST, Routes } from "discord.js";

const token = process.env.DISCORD_TOKEN;
const applicationId = process.env.DISCORD_CLIENT_ID;
if (!token || !applicationId) {
  throw new Error("Set DISCORD_TOKEN and DISCORD_CLIENT_ID in .env before uploading emojis.");
}

const emojiDirectory = path.resolve("emojis");
const outputFile = path.resolve("src/utils/custom-emojis.generated.ts");
const extensions: Record<string, string> = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
};
const rest = new REST({ version: "10" }).setToken(token);
const emojiRoute = Routes.applicationEmojis(applicationId);
const list = await rest.get(emojiRoute) as { items?: Array<{ id: string; name: string; animated?: boolean }> } | Array<{ id: string; name: string; animated?: boolean }>;
const existing = Array.isArray(list) ? list : list.items ?? [];
const customEmojis: Record<string, string> = {};
const files = (await readdir(emojiDirectory)).filter((file) => extensions[path.extname(file).toLowerCase()]);

if (files.length === 0) {
  console.log("No emoji images found in ./emojis. Add PNG, JPG, GIF, or WebP files and run again.");
  process.exit(0);
}

for (const file of files) {
  const extension = path.extname(file).toLowerCase();
  const name = path.basename(file, extension).toLowerCase().replace(/[^a-z0-9_]/g, "_").replace(/^_+|_+$/g, "").slice(0, 32);
  if (!name) {
    console.warn(`Skipping ${file}: its filename does not produce a valid emoji name.`);
    continue;
  }
  const data = await readFile(path.join(emojiDirectory, file));
  const image = `data:${extensions[extension]};base64,${data.toString("base64")}`;
  const previous = existing.find((emoji) => emoji.name === name);
  const route = previous
    ? Routes.applicationEmoji(applicationId, previous.id)
    : emojiRoute;
  const body = { name, image };
  const uploaded = await (previous
    ? rest.patch(route, { body })
    : rest.post(route, { body })) as { id: string; name: string; animated?: boolean };
  customEmojis[name] = `${uploaded.animated ? "<a" : "<"}:${uploaded.name}:${uploaded.id}>`;
  console.log(`${previous ? "Updated" : "Uploaded"} :${name}:`);
}

const source = `// Generated by npm run emojis:upload. Do not edit by hand.\nexport const CUSTOM_EMOJIS: Record<string, string> = ${JSON.stringify(customEmojis, null, 2)};\n`;
await writeFile(outputFile, source, "utf8");
console.log(`Saved ${Object.keys(customEmojis).length} emoji mapping(s) to ${path.relative(process.cwd(), outputFile)}.`);
